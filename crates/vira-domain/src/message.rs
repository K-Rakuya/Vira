use serde::{Deserialize, Serialize};
use std::str::FromStr;

/// Roles in a conversational turn.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    System,
    User,
    Assistant,
    Tool,
}

impl Role {
    /// Returns the lowercase string representation.
    pub fn as_str(&self) -> &'static str {
        match self {
            Role::System => "system",
            Role::User => "user",
            Role::Assistant => "assistant",
            Role::Tool => "tool",
        }
    }
}

impl std::fmt::Display for Role {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.as_str())
    }
}

/// Error returned when parsing a role string fails.
#[derive(thiserror::Error, Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[error("invalid role: '{0}'")]
pub struct RoleParseError(pub String);

impl FromStr for Role {
    type Err = RoleParseError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_ascii_lowercase().as_str() {
            "system" => Ok(Role::System),
            "user" => Ok(Role::User),
            "assistant" => Ok(Role::Assistant),
            "tool" => Ok(Role::Tool),
            other => Err(RoleParseError(other.to_string())),
        }
    }
}

/// A single message entity in a conversation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Message {
    pub id: String,
    pub role: Role,
    pub raw_content: String,
    pub speakable_content: String,
    pub timestamp: u64,
}

impl Message {
    /// Creates a new message with an auto-generated UUID v4 and current UTC timestamp (millis).
    /// Both `raw_content` and `speakable_content` are initialized to `content`.
    pub fn new(role: Role, content: impl Into<String>) -> Self {
        let content = content.into();
        let timestamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_millis() as u64;

        Self {
            id: uuid::Uuid::new_v4().to_string(),
            role,
            raw_content: content.clone(),
            speakable_content: content,
            timestamp,
        }
    }

    /// Convenience constructor for user message.
    pub fn user(content: impl Into<String>) -> Self {
        Self::new(Role::User, content)
    }

    /// Convenience constructor for assistant message.
    pub fn assistant(content: impl Into<String>) -> Self {
        Self::new(Role::Assistant, content)
    }

    /// Convenience constructor for system message.
    pub fn system(content: impl Into<String>) -> Self {
        Self::new(Role::System, content)
    }

    /// Convenience constructor for tool message.
    pub fn tool(content: impl Into<String>) -> Self {
        Self::new(Role::Tool, content)
    }

    /// Sets explicit speakable content (e.g. stripped of markdown, tags, or SSML).
    pub fn with_speakable_content(mut self, speakable: impl Into<String>) -> Self {
        self.speakable_content = speakable.into();
        self
    }

    /// Sets explicit timestamp (e.g. from external source or audio clock).
    pub fn with_timestamp(mut self, timestamp: u64) -> Self {
        self.timestamp = timestamp;
        self
    }

    /// Constructs a message with all explicit fields (e.g. when loading from database).
    pub fn with_id(
        id: impl Into<String>,
        role: Role,
        raw_content: impl Into<String>,
        speakable_content: impl Into<String>,
        timestamp: u64,
    ) -> Self {
        Self {
            id: id.into(),
            role,
            raw_content: raw_content.into(),
            speakable_content: speakable_content.into(),
            timestamp,
        }
    }

    /// Returns true if this message was sent by the user.
    pub fn is_user(&self) -> bool {
        self.role == Role::User
    }

    /// Returns true if this message was generated by the assistant.
    pub fn is_assistant(&self) -> bool {
        self.role == Role::Assistant
    }

    /// Returns true if this message is a system prompt/instruction.
    pub fn is_system(&self) -> bool {
        self.role == Role::System
    }

    /// Returns true if this message is a tool execution result.
    pub fn is_tool(&self) -> bool {
        self.role == Role::Tool
    }

    /// Returns true if content is completely empty.
    pub fn is_empty(&self) -> bool {
        self.raw_content.is_empty() && self.speakable_content.is_empty()
    }
}

impl std::fmt::Display for Message {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "[{}] {}", self.role, self.raw_content)
    }
}
